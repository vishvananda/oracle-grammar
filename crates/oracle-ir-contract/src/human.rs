//! Compact, reversible card code over the normalized Rust model. This is an
//! authoring view, not Oracle text: parsing always ends in strict IR validation.
mod codec;
pub mod defaults;
pub mod document;
mod movement;
pub mod names;
mod syntax;
mod values;
use crate::{
    ir::*,
    ir_schema::{Fields, Schema},
    targets::TargetSelector,
    validate,
};
use serde_json::{Value, json};
use std::sync::OnceLock;
fn schema() -> &'static Schema {
    static SCHEMA: OnceLock<Schema> = OnceLock::new();
    SCHEMA.get_or_init(|| {
        let mut schema = Schema::from_sources(&crate::declarations::authoring_texts())
            .expect("Rust authoring schema");
        // Use the actual Serde constructor names, without a second variant registry.
        for item in crate::declarations::SOURCES.iter().flat_map(|source| {
            syn::parse_file(source.text)
                .expect("Rust model declarations")
                .items
        }) {
            let syn::Item::Enum(item) = item else {
                continue;
            };
            let Some(crate::ir_schema::TypeDef::Enum { variants, .. }) =
                schema.types.get_mut(&item.ident.to_string())
            else {
                continue;
            };
            for variant in item.variants {
                let old = variant.ident.to_string();
                for attr in variant.attrs.iter().filter(|a| a.path().is_ident("serde")) {
                    attr.parse_nested_meta(|meta| {
                        if meta.path.is_ident("rename") {
                            let new: syn::LitStr = meta.value()?.parse()?;
                            if let Some((name, _)) = variants.iter_mut().find(|(n, _)| *n == old) {
                                *name = new.value();
                            }
                        } else if meta.input.peek(syn::Token![=]) {
                            let _: syn::Lit = meta.value()?.parse()?;
                        }
                        Ok(())
                    })
                    .unwrap();
                }
            }
        }
        schema
    })
}
fn checked(card: &UnifiedCard) -> Result<(), String> {
    validate::unified(card)?;
    if !crate::complete::forms(card).named.is_empty() {
        return Err("unreduced Named forms cannot be authored as complete card code".into());
    }
    for face in &card.faces {
        validate::card(face).map_err(|e| format!("{}: {e}", face.name))?;
    }
    Ok(())
}
pub fn write(card: &UnifiedCard) -> Result<String, String> {
    checked(card)?;
    let value = serde_json::to_value(card).map_err(|e| e.to_string())?;
    codec::write(&value).map(|s| s + "\n")
}
pub fn read(text: &str) -> Result<UnifiedCard, String> {
    let node = syntax::parse(text)?;
    let value = codec::read(&node)?;
    let card: UnifiedCard = serde_json::from_value(value.clone()).map_err(|e| e.to_string())?;
    if serde_json::to_value(&card).map_err(|e| e.to_string())? != value {
        return Err("unknown or missing card-code fields".into());
    }
    checked(&card)?;
    Ok(card)
}
/// Metadata is generated by the same Rust policy the reader/writer use.
pub fn editor_metadata() -> Value {
    let schema = schema();
    let mut values = serde_json::Map::new();
    let mut actions = serde_json::Map::new();
    let mut instructions = serde_json::Map::new();
    let mut keyword_actions = serde_json::Map::new();
    let mut object_keyword_actions = serde_json::Map::new();
    let mut add = |owner: String, fields: &Fields| {
        if let Fields::Named(fields) = fields {
            let defaults: serde_json::Map<_, _> = fields
                .iter()
                .filter_map(|(n, t)| defaults::field(&owner, n, t).map(|v| (n.clone(), v)))
                .collect();
            if !defaults.is_empty() {
                values.insert(owner, Value::Object(defaults));
            }
        }
    };
    for (name, d) in &schema.types {
        match d {
            crate::ir_schema::TypeDef::Struct(fields) => add(name.clone(), fields),
            crate::ir_schema::TypeDef::Enum { variants, .. } => {
                for (variant, fields) in variants {
                    add(format!("{name}::{variant}"), fields);
                    if name == "Operation" {
                        actions.insert(variant.clone(), names::action(variant));
                    } else if name == "Instruction" && variant != "Effect" {
                        instructions.insert(variant.clone(), names::instruction(variant));
                    } else if name == "KeywordAction" {
                        keyword_actions
                            .insert(variant.clone(), names::keyword_action(variant, false));
                    } else if name == "ObjectKeywordAction" {
                        object_keyword_actions
                            .insert(variant.clone(), names::keyword_action(variant, true));
                    }
                }
            }
        }
    }
    let targets:Vec<_>=[("any target",TargetSelector::any_target()),("target creature",TargetSelector::creature()),("target planeswalker",TargetSelector::planeswalker()),("target player",TargetSelector::player())].into_iter().map(|(label,select)|{
        let spec=select.clone().into_spec(TargetSlot(0));
        json!({"label":label,"selector":select,"fields":{"kind":spec.kind,"filter":spec.filter,"players":spec.players}})
    }).collect();
    json!({"values":self::values::metadata(),"defaults":values,"targets":targets,"actions":actions,"instructions":instructions,"keyword_actions":keyword_actions,"object_keyword_actions":object_keyword_actions,"references":names::references()})
}
