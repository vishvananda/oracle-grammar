#!/usr/bin/env python3
"""Generate grammar/syntax/counters_named.ebnf from mtgish's CounterName enum.

usage: gen_counters.py <counter.rs> <output.ebnf>
"""
import re
import sys

ODD_SPELLINGS = {"PhylacteryCounter": ["phylactery"], "ManabondCounter": ["manabond"]}


def spelling(variant):
    if variant in ODD_SPELLINGS:
        return ODD_SPELLINGS[variant]
    stem = variant[: -len("Counter")] if variant.endswith("Counter") else variant
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", stem).lower().split()


def main(source, output):
    with open(source, encoding="utf-8") as data:
        text = data.read()
    body = text[text.index("pub enum CounterName {") :]
    body = body[: body.index("\n}")]
    variants = sorted(set(re.findall(r"^\s*([A-Z][A-Za-z0-9]*),\s*$", body, re.M)))
    names = ["cn_" + "_".join(spelling(v)).replace("-", "_") for v in variants]
    lines = ["/* Generated by tools/gen_counters.py from mtgish's CounterName enum. */"]
    joined = " | ".join(names)
    lines.append("counter_name ::= " + joined)
    for variant, name in zip(variants, names):
        terminals = " ".join(f'"{word}"' for word in spelling(variant))
        lines.append(f"/* @sem CounterKind::Named({variant}) */")
        lines.append(f"{name} ::= {terminals}")
    with open(output, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
