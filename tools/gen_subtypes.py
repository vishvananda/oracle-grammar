#!/usr/bin/env python3
"""Generate grammar/syntax/subtypes.ebnf from mtgish's SubType enum.

usage: gen_subtypes.py <mtg_types.rs> <output.ebnf>
"""
import re
import sys

PLURALS = {
    "Equipment": "Equipment", "Plains": "Plains", "Zubera": "Zubera", "Kavu": "Kavu",
    "Elf": "Elves", "Wolf": "Wolves", "Dwarf": "Dwarves", "Werewolf": "Werewolves",
    "Fish": "Fish", "Sheep": "Sheep", "Elk": "Elk", "Ox": "Oxen", "Mouse": "Mice",
    "Fungus": "Fungi", "Cyclops": "Cyclopes", "Sphinx": "Sphinxes", "Fox": "Foxes",
    "Lich": "Liches", "Golem": "Golems", "Djinn": "Djinn", "Efreet": "Efreet",
    "Merfolk": "Merfolk", "Kor": "Kor", "Kithkin": "Kithkin", "Nightstalker": "Nightstalkers",
    "Homunculus": "Homunculi", "Moonfolk": "Moonfolk", "Vedalken": "Vedalken",
    "Aetherborn": "Aetherborn", "Treefolk": "Treefolk", "Volver": "Volvers",
}


def words(name):
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)


def plural(word):
    if word in PLURALS:
        return PLURALS[word]
    if word.endswith(("s", "x", "ch", "sh")):
        return word + "es"
    if word.endswith("y") and word[-2] not in "aeiou":
        return word[:-1] + "ies"
    return word + "s"


def enum_variants(text, name):
    body = text[text.index(f"pub enum {name} {{") :]
    body = body[: body.index("\n}")]
    return {v for v in re.findall(r"^\s*([A-Z][A-Za-z0-9]*),\s*$", body, re.M)
            if re.fullmatch(r"[A-Z][a-z]+(?:[A-Z][a-z]+)*", v)}


def word_rules(name, variants):
    singular, many = [], []
    for variant in sorted(variants):
        parts = words(variant).split(" ")
        singular.append(" ".join(f'"{w}"' for w in parts))
        many.append(" ".join(f'"{w}"' for w in parts[:-1] + [plural(parts[-1])]))
    return ["", "/* @sem () */", f"{name}_word ::= " + " | ".join(singular),
            "", "/* @sem () */", f"{name}_plural_word ::= " + " | ".join(many)]


def main(source, output):
    with open(source, encoding="utf-8") as data:
        text = data.read()
    variants = sorted(enum_variants(text, "SubType"))
    lines = ["/* Generated by tools/gen_subtypes.py from the SubType enum. Do not edit. */", ""]
    singular, plurals, negated, spellings = [], [], [], []
    for variant in variants:
        spelled = words(variant)
        last = spelled.split(" ")[-1]
        many = " ".join(spelled.split(" ")[:-1] + [plural(last)])
        rule = "st_" + variant.lower()
        quoted = " ".join(f'"{w}"' for w in spelled.split(" "))
        spellings.append(quoted)
        quoted_many = " ".join(f'"{w}"' for w in many.split(" "))
        lines += [f"/* @sem ObjectFilter::Subtype({variant}) */", f"{rule} ::= {quoted}", ""]
        singular.append(rule)
        if many != spelled:
            lines += [f"/* @sem ObjectFilter::Subtype({variant}) */", f"{rule}_pl ::= {quoted_many}", ""]
            plurals.append(rule + "_pl")
        else:
            plurals.append(rule)
        if " " not in spelled:
            lines += [f"/* @sem ObjectFilter::Not(ObjectFilter::Subtype({variant})) */",
                      f'{rule}_non ::= "non-{spelled}"', ""]
            negated.append(rule + "_non")
    for name, items in (("subtype", singular), ("subtype_plural", plurals), ("subtype_negated", negated)):
        lines.append(f"{name} ::= " + " | ".join(items))
    # A reference's noun is spelling metadata: AttachedTo already identifies
    # the host, while the enchant ability carries its semantic filter.
    lines += ["", "/* @sem () */", "subtype_word ::= " + " | ".join(spellings)]
    # Retaining an existing creature subtype changes CreatureTypesOf to Add.
    # Other subtype notes leave that operation's replacement mode intact.
    creatures = enum_variants(text, "CreatureType") & set(variants)
    lines += ["", "/* Creature-type choices exclude other subtype families. */",
              "creature_subtype ::= " + " | ".join("st_" + v.lower() for v in sorted(creatures))]
    lines += word_rules("creature_type", creatures)
    lines += word_rules("other_subtype", set(variants) - creatures)
    with open(output, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    print(len(variants), "subtypes")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
